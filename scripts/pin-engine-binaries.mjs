// Pins the engine CLIs Pi Desktop downloads on demand: tarball URL, npm sha512 integrity and
// size per platform, written to src/shared/engine-binaries.generated.ts. The app verifies every
// download against these pins, never against registry metadata fetched at run time.
//
//   node scripts/pin-engine-binaries.mjs                 # Claude Code = installed SDK version
//   node scripts/pin-engine-binaries.mjs --codex 0.160.0 # also re-pin Codex
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..')
const output = join(repo, 'src/shared/engine-binaries.generated.ts')
const argv = process.argv.slice(2)
const flag = (name) => {
  const index = argv.indexOf(name)
  return index >= 0 ? argv[index + 1] : undefined
}

const PLATFORMS = [
  'darwin-arm64',
  'darwin-x64',
  'linux-x64',
  'linux-arm64',
  'win32-x64',
  'win32-arm64'
]
const CODEX_TRIPLES = {
  'darwin-arm64': 'aarch64-apple-darwin',
  'darwin-x64': 'x86_64-apple-darwin',
  'linux-x64': 'x86_64-unknown-linux-musl',
  'linux-arm64': 'aarch64-unknown-linux-musl',
  'win32-x64': 'x86_64-pc-windows-msvc',
  'win32-arm64': 'aarch64-pc-windows-msvc'
}

async function registry(name, version) {
  const response = await fetch(
    `https://registry.npmjs.org/${name.replace('/', '%2F')}/${encodeURIComponent(version)}`
  )
  if (!response.ok) throw new Error(`${name}@${version}: ${response.status}`)
  const manifest = await response.json()
  const probe = await fetch(manifest.dist.tarball, { headers: { range: 'bytes=0-0' } })
  const size = Number(/\/(\d+)$/.exec(probe.headers.get('content-range') ?? '')?.[1] ?? 0)
  await probe.body?.cancel()
  return { tarball: manifest.dist.tarball, integrity: manifest.dist.integrity, size }
}

async function claude() {
  const sdk = JSON.parse(
    await readFile(join(repo, 'node_modules/@anthropic-ai/claude-agent-sdk/package.json'), 'utf8')
  )
  const platforms = {}
  for (const platform of PLATFORMS) {
    const pin = await registry(`@anthropic-ai/claude-agent-sdk-${platform}`, sdk.version)
    const exe = platform.startsWith('win32') ? 'claude.exe' : 'claude'
    platforms[platform] = { ...pin, root: 'package/', executable: exe }
  }
  return { version: sdk.version, platforms }
}

async function codex(version) {
  const platforms = {}
  for (const platform of PLATFORMS) {
    const pin = await registry('@openai/codex', `${version}-${platform}`)
    const triple = CODEX_TRIPLES[platform]
    const exe = platform.startsWith('win32') ? 'bin/codex.exe' : 'bin/codex'
    platforms[platform] = {
      ...pin,
      root: `package/vendor/${triple}/`,
      executable: exe,
      // Voice mode is not used by Pi Desktop; skipping it saves ~70 MB on disk.
      skip: ['codex-resources/voice/']
    }
  }
  return { version, platforms }
}

let previous = {}
try {
  const text = await readFile(output, 'utf8')
  previous = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1))
} catch {
  // First run.
}
const codexVersion = flag('--codex')
const pins = {
  claude: await claude(),
  codex: codexVersion ? await codex(codexVersion) : previous.codex
}
if (!pins.codex) throw new Error('Codex has never been pinned; pass --codex <version>')
await writeFile(
  output,
  `// Generated by scripts/pin-engine-binaries.mjs. Do not edit by hand.\n` +
    `export const ENGINE_BINARY_PINS = ${JSON.stringify(pins, null, 2)} as const\n`
)
console.log(`Pinned Claude Code ${pins.claude.version} and Codex ${pins.codex.version}`)
